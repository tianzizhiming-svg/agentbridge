def print_step(msg):
    print("=" * 60)
    print("[STEP] " + msg)
    print("=" * 60)


def run_cmd(cmd, check=False, capture=True):
    """Run a shell command and return (returncode, stdout, stderr)."""
    try:
        result = subprocess.run(
            cmd,
            shell=True,
            capture_output=capture,
            text=True,
            timeout=60,
        )
        if check and result.returncode != 0:
            print("  Command failed: " + cmd)
            if result.stderr:
                print("  stderr: " + result.stderr.strip())
        return result.returncode, result.stdout, result.stderr
    except subprocess.TimeoutExpired:
        print("  Command timed out: " + cmd)
        return 1, "", "timeout"
    except Exception as e:
        print("  Command error: " + str(e))
        return 1, "", str(e)


def write_file_from_b64(b64_content, dest_path):
    """Decode base64 and write binary content to dest_path."""
    data = base64.b64decode(b64_content)
    os.makedirs(os.path.dirname(dest_path), exist_ok=True)
    with open(dest_path, "wb") as f:
        f.write(data)
    print("  Written: " + dest_path + " (" + str(len(data)) + " bytes)")
    return len(data)


def verify_python_syntax(file_path):
    """Verify Python syntax of a file using py_compile."""
    try:
        py_compile.compile(file_path, doraise=True)
        print("  [PASS] Syntax OK: " + file_path)
        return True
    except py_compile.PyCompileError as e:
        print("  [FAIL] Syntax error in " + file_path + ": " + str(e))
        return False
    except Exception as e:
        print("  [FAIL] Error checking " + file_path + ": " + str(e))
        return False


def validate_json_file(file_path):
    """Validate that a file contains valid JSON."""
    try:
        with open(file_path, "r", encoding="utf-8") as f:
            json.load(f)
        print("  [PASS] Valid JSON: " + file_path)
        return True
    except json.JSONDecodeError as e:
        print("  [FAIL] Invalid JSON in " + file_path + ": " + str(e))
        return False
    except Exception as e:
        print("  [FAIL] Error reading " + file_path + ": " + str(e))
        return False


def test_endpoint(url, expected_status):
    """Test an HTTP GET endpoint and compare status code."""
    try:
        req = urllib.request.Request(url, method="GET")
        try:
            resp = urllib.request.urlopen(req, timeout=10)
            status = resp.getcode()
        except urllib.error.HTTPError as e:
            status = e.code
        if status == expected_status:
            print("  [PASS] " + url + " -> " + str(status) + " (expected " + str(expected_status) + ")")
            return True
        else:
            print("  [FAIL] " + url + " -> " + str(status) + " (expected " + str(expected_status) + ")")
            return False
    except urllib.error.URLError as e:
        print("  [FAIL] " + url + " -> Connection error: " + str(e))
        return False
    except Exception as e:
        print("  [FAIL] " + url + " -> Error: " + str(e))
        return False


